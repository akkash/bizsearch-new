function norm(value?: string | null): string {
  return (value || "").trim().toLowerCase().replace(/\s+/g, " ");
}

export function coordinatesForPlace(
  city?: string | null,
  state?: string | null
): { latitude: number; longitude: number } | null {
  const cityKey = norm(city);
  const stateKey = norm(state);
  const cityPoint = cityKey ? CITY[cityKey] : undefined;
  if (cityPoint) return { latitude: cityPoint[0], longitude: cityPoint[1] };
  const statePoint = stateKey ? STATE[stateKey] : undefined;
  if (statePoint) return { latitude: statePoint[0], longitude: statePoint[1] };
  return null;
}
